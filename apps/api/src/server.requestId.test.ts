/**
 * #860: production Fastify generates server-owned UUIDv4 request IDs.
 * Client request-id headers are untrusted claims and must not override them.
 *
 * This test boots the actual production entrypoint, not a copied Fastify
 * constructor. It verifies error envelopes, Pino correlation, and distinct
 * IDs across independent processes and a process restart.
 */
import { describe, expect, it } from "vitest";
import { spawn } from "node:child_process";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createPostgresDatabase } from "@exam/db/postgres";
import { getIsolatedTestDb, resolveTestDbUrl } from "@exam/db/testDb";
import { addSearchPathToUrl } from "@exam/db/testIsolation";

const __dirname = dirname(fileURLToPath(import.meta.url));
const SERVER_PATH = resolve(__dirname, "server.ts");
const TSX_IMPORT_SPECIFIER = import.meta.resolve("tsx");

const BOOT_TIMEOUT_MS = 45_000;

/** UUIDv4: version 4, RFC 4122 variant, generated by node:crypto. */
const UUID_V4_REQUEST_ID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

async function pgReachable(url: string): Promise<boolean> {
  const conn = await createPostgresDatabase(url);
  try {
    await conn.sql`SELECT 1`;
    return true;
  } catch {
    return false;
  } finally {
    await conn.sql.end();
  }
}

const PG_UP = await pgReachable(resolveTestDbUrl());
const PG_DESCRIBE = PG_UP ? describe : describe.skip;

interface PinoLine {
  reqId?: string;
  msg?: string;
  res?: { statusCode?: number };
  // #925: the incoming line carries the trusted route template (or the
  // fixed placeholder) — never the raw url.
  req?: { route?: string; method?: string; url?: string | undefined };
  responseTime?: number;
}

function parsePinoLines(stdout: string): PinoLine[] {
  return stdout
    .split("\n")
    .filter((l) => l.startsWith("{"))
    .map((l) => {
      try {
        return JSON.parse(l) as PinoLine;
      } catch {
        return null;
      }
    })
    .filter((l): l is PinoLine => l !== null);
}

interface BootedServer {
  port: number;
  stdout: () => string;
  close: () => Promise<{ stdout: string; stderr: string }>;
}

async function bootProductionServer(): Promise<BootedServer> {
  const iso = await getIsolatedTestDb("api-server-request-id");
  // Shared-DB fallback (isolation disabled) has no schemaName; the base
  // test URL is then correct as-is.
  const baseUrl = iso.databaseUrl ?? resolveTestDbUrl();
  const childDbUrl = iso.schemaName
    ? addSearchPathToUrl(baseUrl, iso.schemaName)
    : baseUrl;

  const childPort = 20_000 + Math.floor(Math.random() * 20_000);
  const child = spawn(
    process.execPath,
    ["--import", TSX_IMPORT_SPECIFIER, SERVER_PATH],
    {
      // Closed-whitelist managed test profile (same shape as
      // server.shutdown.test.ts): the child must never read the developer
      // `.env`, and the DB target is the test-owned URL below.
      env: {
        APP_MODE: "test",
        NODE_ENV: "test",
        HOST: "127.0.0.1",
        APP_PORT: String(childPort),
        TEST_DATABASE_URL: childDbUrl,
        JWT_SECRET: "request-id-guard-test-jwt-secret-0123456789abcdef",
        EMAIL_ENABLED: "false",
      },
      stdio: ["ignore", "pipe", "pipe"],
    },
  );
  let stdout = "";
  let stderr = "";
  child.stdout.setEncoding("utf8");
  child.stderr.setEncoding("utf8");
  child.stdout.on("data", (d: string) => {
    stdout += d;
  });
  child.stderr.on("data", (d: string) => {
    stderr += d;
  });

  const port = await new Promise<number>((resolvePort, reject) => {
    const bootTimer = setTimeout(
      () =>
        reject(
          new Error(
            `server did not boot within ${BOOT_TIMEOUT_MS}ms\nstdout: ${stdout}\nstderr: ${stderr}`,
          ),
        ),
      BOOT_TIMEOUT_MS,
    );
    const poll = setInterval(() => {
      const match = stdout.match(
        /Server listening at http:\/\/127\.0\.0\.1:(\d+)/,
      );
      if (match) {
        clearInterval(poll);
        clearTimeout(bootTimer);
        resolvePort(Number(match[1]));
      }
    }, 50);
    child.on("close", () => {
      clearInterval(poll);
      clearTimeout(bootTimer);
      reject(
        new Error(
          `server exited before listening\nstdout: ${stdout}\nstderr: ${stderr}`,
        ),
      );
    });
  });

  return {
    port,
    stdout: () => stdout,
    close: async () => {
      child.kill("SIGTERM");
      const done = await new Promise<{ stdout: string; stderr: string }>(
        (resolveClose) => {
          const timer = setTimeout(() => {
            child.kill("SIGKILL");
            resolveClose({ stdout, stderr });
          }, 10_000);
          child.on("close", () => {
            clearTimeout(timer);
            resolveClose({ stdout, stderr });
          });
        },
      );
      await iso.cleanup();
      return done;
    },
  };
}

PG_DESCRIBE("production UUIDv4 requestId and header guard (#860)", () => {
  it("ignores request-id / X-Request-Id headers and keeps error envelope ↔ pino reqId identical", async () => {
    const server = await bootProductionServer();
    try {
      const forgedLower = "forged-lower-header-id-prt";
      const forgedUpper = "forged-upper-header-id-prt";

      // Probe 1: forged headers on an unmatched /api route → the canonical
      // 404 error envelope. The envelope's requestId must be the server's
      // own UUIDv4 id, never a header echo.
      const notFoundPath = `/api/no-such-route-${crypto.randomUUID()}`;
      const res = await fetch(
        `http://127.0.0.1:${server.port}${notFoundPath}`,
        {
          headers: { "request-id": forgedLower, "X-Request-Id": forgedUpper },
        },
      );
      expect(res.status).toBe(404);
      const body = (await res.json()) as {
        error: { code: string; requestId: string };
      };
      expect(body.error.code).toBe("RESOURCE_NOT_FOUND");
      expect(body.error.requestId).toMatch(UUID_V4_REQUEST_ID_RE);
      expect(body.error.requestId).not.toBe(forgedLower);
      expect(body.error.requestId).not.toBe(forgedUpper);

      // Probe 2: the same forged headers on a successful request.
      const healthRes = await fetch(
        `http://127.0.0.1:${server.port}/api/health`,
        { headers: { "request-id": forgedLower, "X-Request-Id": forgedUpper } },
      );
      expect(healthRes.ok).toBe(true);

      // Probe 3: envelope ↔ pino correspondence for the 404 request. Pino
      // stamps every line of a request with the SAME reqId the error handler
      // passed to buildErrorResponse (request.id). The "incoming request"
      // line carries the #925 route field (never a raw url); the completion
      // line carries res.statusCode — correlate the pair through reqId.
      let requestLine: PinoLine | undefined;
      await expect
        .poll(() => {
          const lines = parsePinoLines(server.stdout());
          const reqId404 = lines
            .filter((l) => l.res?.statusCode === 404 && l.reqId)
            .map((l) => l.reqId!)
            .at(-1);
          requestLine = lines.find(
            (line) =>
              line.msg === "incoming request" && line.reqId === reqId404,
          );
          return requestLine?.reqId;
        })
        .toMatch(UUID_V4_REQUEST_ID_RE);
      const reqId = requestLine!.reqId!;
      expect(reqId).not.toBe(forgedLower);
      expect(reqId).not.toBe(forgedUpper);
      expect(body.error.requestId).toBe(reqId);
      // #925: the incoming line for an unmatched route carries the trusted
      // template/placeholder — never the raw path bytes.
      expect(requestLine!.req?.url).toBeUndefined();
      expect(requestLine!.req?.route).toBeTruthy();
      expect(requestLine!.req?.route).not.toContain(notFoundPath);

      const completionLines = parsePinoLines(server.stdout()).filter(
        (line) => line.reqId === reqId && line.res?.statusCode === 404,
      );
      expect(
        completionLines.length,
        `expected a pino completion line for ${notFoundPath}`,
      ).toBeGreaterThanOrEqual(1);

      // Probe 4 (#925): an unmatched NON-/api path with a query canary —
      // the root-scope 404 boundary (registerRootNotFoundBoundary) must
      // answer the same JSON envelope, and Fastify's default basic404
      // message ("Route <raw url> not found" — raw URL bytes) must never
      // reach the log stream.
      const rootCanary = `EXAMAUDIT-CANARY-LOG-root-${crypto.randomUUID()}`;
      const rootRes = await fetch(
        `http://127.0.0.1:${server.port}/outside-api?token=${rootCanary}`,
      );
      expect(rootRes.status).toBe(404);
      const rootBody = (await rootRes.json()) as {
        error: { code: string; requestId: string };
      };
      expect(rootBody.error.code).toBe("RESOURCE_NOT_FOUND");
      expect(rootBody.error.requestId).toMatch(UUID_V4_REQUEST_ID_RE);
      await new Promise((r) => setTimeout(r, 50));
      expect(server.stdout()).not.toContain(rootCanary);
      expect(server.stdout()).not.toContain("Route GET");

      // The server-generated UUIDv4 format on the wire: no log line anywhere in
      // this boot may carry a forged header value as its reqId, and the
      // observed request ids remain UUIDv4, not local counters.
      const allReqIds = parsePinoLines(server.stdout())
        .map((l) => l.reqId)
        .filter((id): id is string => typeof id === "string");
      expect(allReqIds.length).toBeGreaterThanOrEqual(1);
      for (const id of allReqIds) {
        expect(id).toMatch(UUID_V4_REQUEST_ID_RE);
        expect(id).not.toBe(forgedLower);
        expect(id).not.toBe(forgedUpper);
      }
    } finally {
      await server.close();
    }
  }, 120_000);

  it("assigns different UUIDv4 request IDs across processes and after restart", async () => {
    const active = new Set<BootedServer>();
    const boot = async () => {
      const server = await bootProductionServer();
      active.add(server);
      return server;
    };
    const fetchRequestId = async (server: BootedServer) => {
      const path = `/api/uuid-correlation-probe-${crypto.randomUUID()}`;
      const response = await fetch(`http://127.0.0.1:${server.port}${path}`);
      expect(response.status).toBe(404);
      const body = (await response.json()) as {
        error: { requestId: string };
      };
      expect(body.error.requestId).toMatch(UUID_V4_REQUEST_ID_RE);
      return body.error.requestId;
    };

    try {
      const a = await boot();
      const b = await boot();
      const [aId, bId] = await Promise.all([
        fetchRequestId(a),
        fetchRequestId(b),
      ]);
      expect(aId).not.toBe(bId);

      await a.close();
      active.delete(a);
      const restarted = await boot();
      const restartedId = await fetchRequestId(restarted);
      expect(new Set([aId, bId, restartedId]).size).toBe(3);
    } finally {
      for (const server of active) {
        await server.close();
      }
    }
  }, 180_000);
});
